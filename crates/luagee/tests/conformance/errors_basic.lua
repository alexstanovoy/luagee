-- error/pcall/xpcall/assert semantics without relying on message wording.
local function strip(m) return (tostring(m):gsub("^[^:]*:%d+: ", "")) end
print(pcall(error))
print(pcall(error, nil))
print(pcall(error, "msg", 0))
print(select("#", pcall(error)))
print(pcall(error, 42))
print(pcall(error, true))
local obj = {code = 5}
local ok, e = pcall(error, obj)
print(ok, e == obj, e.code)
print(pcall(function() error("plain") end) == false, strip(select(2, pcall(function() error("plain") end))))
print(strip(select(2, pcall(function() error("lvl1", 1) end))))
print(strip(select(2, pcall(function() error("lvl2", 2) end))))
print(select(2, pcall(function() error("lvl0", 0) end)))
print(select(2, pcall(function() error() end)))
print(type(select(2, pcall(function() error({}) end))))
local function thrower() error("from thrower", 2) end
local function caller() thrower() end
local ok2, m2 = pcall(caller)
print(ok2, m2:find("^[^:]*:%d+: from thrower") ~= nil)
print(select("#", pcall(function() return 1, 2, 3 end)), pcall(function() return 1, 2, 3 end))
print(pcall(pcall, error, "x"))
print((pcall(pcall)))
print(xpcall(function() return "fine", 2 end, function(m) return "handled" end))
print(xpcall(function() error("bad", 0) end, function(m) return "handled: " .. m end))
print(xpcall(function() error({1}) end, function(m) return type(m) end))
print(xpcall(function() local x = nil; return x.y end, function(m) return "H" end))
print(xpcall(error, function(m) return "args" end, "e"))
print(select("#", xpcall(function() error("z", 0) end, function(m) return 1, 2 end)))
print(xpcall(function() error("in handler test", 0) end, function(m) error("handler fails", 0) end) == false)
print(pcall(xpcall) == false, pcall(xpcall, print) == false)
print(assert(1, "unused"), assert("v"), select("#", assert(1, 2, 3)))
print(pcall(assert, false))
print(pcall(assert, nil, "custom message"))
print(type(select(2, pcall(assert, false, {1}))))
print(select(2, pcall(assert, false, 42)))
print(select("#", pcall(assert)))
print(pcall(assert, false, nil))
print(strip(select(2, pcall(function() assert(false) end))))
print(strip(select(2, pcall(function() assert(1 == 2, "math is broken") end))))
local nested = pcall(function() pcall(error, "inner") error("outer", 0) end)
print(nested)
local ok3, m3 = pcall(function() local ok, m = pcall(error, "inner", 0) error(m .. " rethrown", 0) end)
print(m3)
print(tostring(nil), tostring(false), tostring(0/0 ~= 0/0))
local depth = 0
local function recurse() depth = depth + 1 return 1 + recurse() end
local ok4 = pcall(recurse)
print(ok4, depth > 100)
local function finally(f, cleanup) local ok, err = pcall(f) cleanup() if not ok then error(err, 0) end end
print(pcall(finally, function() error("work failed", 0) end, function() print("cleanup ran") end))
