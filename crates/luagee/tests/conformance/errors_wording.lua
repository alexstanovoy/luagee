-- LuaJIT's wording of runtime error messages (the reference), with the chunk:line prefix stripped.
local function msg(f, ...)
  local ok, m = pcall(f, ...)
  if ok then return "no error" end
  return (tostring(m):gsub("^[^:]*:%d+: ", ""))
end
