-- Number literal forms: decimal, fractions, exponents, hex, hex floats, long digit strings.
local function show(...) print(...) end
show(0, 1, 42, 007, 1e2, 1E2, 1e+2, 1e-2, 2.5e3)
show(.5, 5., 5.0, 0.5e1, .5e-1, 3e0)
show(0x0, 0x1F, 0xff, 0XFF, 0xDeadBeef, 0x7fffffff, 0x80000000, 0xffffffff, 0x100000000)
show(0x1p4, 0x1.8p3, 0x.8p1, 0xA.8p0, 0x1P-1, 0x10p-4)
show(123456789012345678901234567890, 0.1234567890123456789, 1e308, 1e309, -1e309, 1e-400)
show(9007199254740992, 9007199254740993, 18446744073709551615, 18446744073709551616)
show(1e15, 1e16, 1e100, 123456789012345, 1234567890123456)
show(0.1, 0.5, 1/3, 100, 1e2 == 100, 0x10 == 16)
show(3 .. 4, 3. .. 4)
show(1 .. 2 == "12")
show(math.type == nil)
show(0xffffffffffffffff, 0x7fffffffffffffff)
show(5 % 3, 2^-1, 2^0.5 == math.sqrt(2))
show(1e0, 1E-0, 0e0, 0.0, -0.0)
show(#"1e5", 1e5 .. "")
local f, e = loadstring("return 1..2")
show(f == nil)
f = loadstring("return 0x")
show(f == nil)
f = loadstring("return 1e")
show(f == nil)
f = loadstring("return 3x")
show(f == nil)
show(f == nil)
show(f == nil)
f = loadstring("return 0xg")
show(f == nil)
show(loadstring("return 0x1p")  == nil)
show(loadstring("return 08")(), loadstring("return 010")())
show(loadstring("return 1e+")  == nil)
show(loadstring("return 0xA.8")(), loadstring("return 0x.1")())
show(loadstring("return 1.e2")(), loadstring("return 1.5.2") == nil)
